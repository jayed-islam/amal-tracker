/// Backend এর getPositionFromCumulativeAyah এর হুবহু client-side কপি —
/// ইনপুট দেওয়ার সময় "এখন কোথায় থাকবেন" live preview দেখানোর জন্য।
({int surahNumber, int ayahInSurah}) positionFromCumulativeAyah(
    int cumulativeAyah) {
  var remaining = cumulativeAyah;
  for (var i = 0; i < kSurahAyahCounts.length; i++) {
    if (remaining <= kSurahAyahCounts[i]) {
      return (surahNumber: i + 1, ayahInSurah: remaining < 1 ? 1 : remaining);
    }
    remaining -= kSurahAyahCounts[i];
  }
  return (surahNumber: 114, ayahInSurah: kSurahAyahCounts[113]);
}
